CREATE TABLE peer_rooms (
 id VARCHAR(36) PRIMARY KEY,
 host_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 guest_id VARCHAR(36) REFERENCES app_users(id),
 interviewer_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 title VARCHAR(120) NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'WAITING' CHECK(status IN ('WAITING','ACTIVE','COMPLETED')),
 epoch INT NOT NULL DEFAULT 0,
 revision INT NOT NULL DEFAULT 0,
 content_revision INT NOT NULL DEFAULT 0,
 created_ms BIGINT NOT NULL,
 expires_ms BIGINT NOT NULL,
 started_ms BIGINT,
 ended_ms BIGINT
);
CREATE INDEX idx_peer_host ON peer_rooms(host_id,created_ms);
CREATE INDEX idx_peer_guest ON peer_rooms(guest_id,created_ms);
CREATE TABLE peer_members (
 room_id VARCHAR(36) NOT NULL REFERENCES peer_rooms(id) ON DELETE CASCADE,
 user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 client_id VARCHAR(36), seen_ms BIGINT NOT NULL DEFAULT 0,
 mic BOOLEAN NOT NULL DEFAULT FALSE, camera BOOLEAN NOT NULL DEFAULT FALSE,
 consent BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(room_id,user_id)
);
CREATE TABLE peer_signals (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id VARCHAR(36) NOT NULL REFERENCES peer_rooms(id) ON DELETE CASCADE,
 sender_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 epoch INT NOT NULL, kind VARCHAR(20) NOT NULL, body TEXT NOT NULL,
 created_ms BIGINT NOT NULL
);
CREATE INDEX idx_peer_signal_cursor ON peer_signals(room_id,epoch,seq);
CREATE TABLE peer_notes (
 id VARCHAR(36) PRIMARY KEY,
 room_id VARCHAR(36) NOT NULL REFERENCES peer_rooms(id) ON DELETE CASCADE,
 user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 source VARCHAR(12) NOT NULL CHECK(source IN ('note','transcript')),
 speaker_role VARCHAR(15) NOT NULL,
 content TEXT NOT NULL, created_ms BIGINT NOT NULL
);
CREATE INDEX idx_peer_notes_room ON peer_notes(room_id,created_ms);
CREATE TABLE peer_feedback (
 room_id VARCHAR(36) NOT NULL REFERENCES peer_rooms(id) ON DELETE CASCADE,
 author_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 clarity INT NOT NULL CHECK(clarity BETWEEN 1 AND 5),
 strengths VARCHAR(2000) NOT NULL, improvements VARCHAR(2000) NOT NULL,
 PRIMARY KEY(room_id,author_id)
);
CREATE TABLE peer_reports (
 room_id VARCHAR(36) NOT NULL REFERENCES peer_rooms(id) ON DELETE CASCADE,
 user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 result_json TEXT NOT NULL, created_ms BIGINT NOT NULL,
 PRIMARY KEY(room_id,user_id)
);
